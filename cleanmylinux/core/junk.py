"""System junk discovery and cleanup (caches, logs, trash, package leftovers)."""

import glob
import os
import re
from dataclasses import dataclass, field

from . import privileged
from .utils import HOME, Throttle, clear_contents, path_size, remove_path

CACHE = os.path.join(HOME, ".cache")

BROWSER_CACHES = {
    "google-chrome": "Google Chrome", "chromium": "Chromium", "mozilla": "Firefox",
    "BraveSoftware": "Brave", "vivaldi": "Vivaldi", "opera": "Opera",
    "microsoft-edge": "Microsoft Edge", "librewolf": "LibreWolf", "thorium": "Thorium",
}

DEV_CACHES = {
    "~/.cache/pip": "pip", "~/.cache/pypoetry/cache": "Poetry", "~/.cache/uv": "uv",
    "~/.npm/_cacache": "npm", "~/.cache/yarn": "Yarn", "~/.yarn/berry/cache": "Yarn Berry",
    "~/.cache/pnpm": "pnpm", "~/.local/share/pnpm/store": "pnpm store",
    "~/.cache/go-build": "Go build cache", "~/.cargo/registry/cache": "Cargo registry",
    "~/.gradle/caches": "Gradle", "~/.cache/composer": "Composer",
    "~/.cache/node-gyp": "node-gyp", "~/.cache/electron": "Electron downloads",
    "~/.cache/bazel": "Bazel",
}

# ~/.cache entries that are reported by a dedicated category instead.
CACHE_EXCLUDE = {"thumbnails", *BROWSER_CACHES}
ROTATED = re.compile(r"\.(gz|xz|bz2|zst|old)$|\.\d+$")


@dataclass
class JunkItem:
    label: str
    size: int
    paths: list = field(default_factory=list)
    mode: str = "remove"  # remove | contents | root
    root_action: str = ""
    selected: bool = True
    detail: str = ""


@dataclass
class JunkCategory:
    id: str
    name: str
    description: str
    icon: str
    items: list = field(default_factory=list)
    needs_root: bool = False

    @property
    def size(self):
        return sum(i.size for i in self.items)

    @property
    def selected_size(self):
        return sum(i.size for i in self.items if i.selected)


def _expand(p):
    return os.path.expanduser(p)


def _item(path, label=None, cancel=None, **kw):
    size = path_size(path, cancel)
    return JunkItem(label or os.path.basename(path), size, [path], detail=path, **kw)


def _user_cache(cancel, dev_paths):
    cat = JunkCategory("user-cache", "User Cache Files",
                       "Temporary data apps keep in ~/.cache. Apps rebuild it as needed; "
                       "quit running apps for best results.", "folder-symbolic")
    try:
        entries = sorted(os.scandir(CACHE), key=lambda e: e.name.lower())
    except OSError:
        return cat
    for entry in entries:
        if entry.name in CACHE_EXCLUDE or entry.path in dev_paths:
            continue
        cat.items.append(_item(entry.path, cancel=cancel))
    return cat


def _browser_cache(cancel):
    cat = JunkCategory("browser-cache", "Browser Cache",
                       "Cached web pages, images and scripts. Browsing history, cookies "
                       "and passwords are not touched.", "web-browser-symbolic")
    for name, label in BROWSER_CACHES.items():
        path = os.path.join(CACHE, name)
        if os.path.isdir(path):
            cat.items.append(_item(path, label, cancel))
    for path in sorted(glob.glob(os.path.join(HOME, ".var/app/*/cache"))):
        app_id = path.split(os.sep)[-2]
        cat.items.append(_item(path, f"{app_id} (Flatpak)", cancel, mode="contents"))
    return cat


def _thumbnails(cancel):
    cat = JunkCategory("thumbnails", "Thumbnail Cache",
                       "Preview images generated by the file manager.", "image-x-generic-symbolic")
    path = os.path.join(CACHE, "thumbnails")
    if os.path.isdir(path):
        cat.items.append(_item(path, "File manager thumbnails", cancel, mode="contents"))
    return cat


def _dev_caches(cancel):
    cat = JunkCategory("dev-cache", "Developer Caches",
                       "Package manager download caches. They are re-downloaded when needed.",
                       "application-x-executable-symbolic")
    for raw, label in DEV_CACHES.items():
        path = _expand(raw)
        if os.path.isdir(path):
            cat.items.append(_item(path, label, cancel, mode="contents"))
    return cat


def _user_logs(cancel):
    cat = JunkCategory("user-logs", "User Log Files",
                       "Old session logs and crash dumps from your account.", "text-x-generic-symbolic")
    patterns = ["~/.xsession-errors.old", "~/.local/share/xorg/*.old",
                "~/.local/share/xorg/*.log.old",
                "~/.config/*/Crash Reports/completed", "~/.config/*/Crash Reports/pending"]
    seen = set()
    for pattern in patterns:
        for path in glob.glob(_expand(pattern)):
            if path not in seen:
                seen.add(path)
                cat.items.append(_item(path, os.path.relpath(path, HOME), cancel))
    return cat


def _broken_downloads(cancel):
    cat = JunkCategory("downloads", "Incomplete Downloads",
                       "Partial files left behind by interrupted browser downloads.",
                       "folder-download-symbolic")
    downloads = os.path.join(HOME, "Downloads")
    for pattern in ("*.part", "*.crdownload", "*.download", "*.partial"):
        for path in glob.glob(os.path.join(downloads, pattern)):
            cat.items.append(_item(path, cancel=cancel))
    return cat


def trash_locations():
    """All trash directories that belong to the current user."""
    locations = [os.path.join(HOME, ".local/share/Trash")]
    uid = os.getuid()
    for base in glob.glob(f"/media/{os.environ.get('USER', '')}/*") + glob.glob("/mnt/*"):
        for name in (f".Trash-{uid}", f".Trash/{uid}"):
            path = os.path.join(base, name)
            if os.path.isdir(path):
                locations.append(path)
    return locations


def _trash(cancel):
    cat = JunkCategory("trash", "Trash Bins",
                       "Files you have already moved to the Trash, on every drive.",
                       "user-trash-full-symbolic")
    for location in trash_locations():
        parts = [os.path.join(location, d) for d in ("files", "info", "expunged")]
        parts = [p for p in parts if os.path.isdir(p)]
        size = sum(path_size(p, cancel) for p in parts)
        if size:
            label = "Home Trash" if location.startswith(HOME) else f"Trash on {os.path.dirname(location)}"
            cat.items.append(JunkItem(label, size, parts, mode="contents", detail=location))
    return cat


def _system_junk(cancel):
    cat = JunkCategory("system", "System Junk",
                       "Package downloads, old system logs and crash reports. "
                       "Requires your administrator password.", "dialog-password-symbolic",
                       needs_root=True)
    apt = sum(path_size(p) for p in glob.glob("/var/cache/apt/archives/*.deb")
              + glob.glob("/var/cache/apt/archives/partial/*") + glob.glob("/var/cache/apt/*.bin"))
    if apt:
        cat.items.append(JunkItem("APT package cache", apt, mode="root", root_action="apt-clean",
                                  detail="/var/cache/apt"))
    journal = path_size("/var/log/journal", cancel)
    excess = journal - 64 * 1000 * 1000
    if excess > 0:
        cat.items.append(JunkItem("Systemd journal (keep newest 64 MB)", excess, mode="root",
                                  root_action="journal-vacuum", detail="/var/log/journal"))
    rotated = 0
    for root, dirs, files in os.walk("/var/log"):
        if root.startswith("/var/log/journal"):
            dirs[:] = []
            continue
        for name in files:
            if ROTATED.search(name):
                try:
                    rotated += os.lstat(os.path.join(root, name)).st_size
                except OSError:
                    pass
    if rotated:
        cat.items.append(JunkItem("Rotated system logs", rotated, mode="root",
                                  root_action="rotated-logs", detail="/var/log"))
    crash = path_size("/var/crash")
    if crash:
        cat.items.append(JunkItem("System crash reports", crash, mode="root",
                                  root_action="crash-reports", detail="/var/crash"))
    return cat


SCANNERS = [
    ("System Junk", _system_junk),
    ("User Cache", None),  # needs dev cache paths; handled in scan()
    ("Browser Cache", _browser_cache),
    ("Thumbnails", _thumbnails),
    ("Developer Caches", _dev_caches),
    ("Logs", _user_logs),
    ("Downloads", _broken_downloads),
    ("Trash", _trash),
]


def scan(progress=None, cancel=None, include_trash=True):
    """Return the list of non-empty junk categories, largest first."""
    report = Throttle(progress)
    dev_paths = {_expand(p) for p in DEV_CACHES}
    categories = []
    for index, (label, scanner) in enumerate(SCANNERS):
        if cancel is not None and cancel.is_set():
            break
        if scanner is _trash and not include_trash:
            continue
        report(f"Scanning {label}…", index / len(SCANNERS), force=True)
        cat = _user_cache(cancel, dev_paths) if scanner is None else scanner(cancel)
        cat.items = sorted((i for i in cat.items if i.size > 0), key=lambda i: -i.size)
        if cat.items:
            categories.append(cat)
    report("Done", 1.0, force=True)
    return categories


def clean(categories, progress=None):
    """Clean all selected items. Returns (freed_bytes, errors)."""
    report = Throttle(progress)
    freed, errors = 0, []
    root_items = []
    selected = [i for c in categories for i in c.items if i.selected]
    for index, item in enumerate(selected):
        if item.mode == "root":
            root_items.append(item)
            continue
        report(f"Cleaning {item.label}…", index / max(len(selected), 1))
        for path in item.paths:
            freed += clear_contents(path) if item.mode == "contents" else remove_path(path)
    if root_items:
        report("Waiting for administrator authorization…", 0.95, force=True)
        try:
            results = privileged.run_root([i.root_action for i in root_items])
        except privileged.AuthCancelled:
            errors.append("System junk skipped: authorization cancelled")
            results = {}
        except RuntimeError as exc:
            errors.append(str(exc))
            results = {}
        for item in root_items:
            ok, out = results.get(item.root_action, (False, ""))
            if ok:
                freed += item.size
            elif results:
                errors.append(f"{item.label}: {out}")
    report("Done", 1.0, force=True)
    return freed, errors
